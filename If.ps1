Write-Host "Bugun darsga kim kelgan?"
 $bola =  Read-Host
if ( $bola -ceq "Sardor") {
    Write-host $bola " darsga kelgan"

}elseif ( $bola -ceq "Samir") {
    Write-host $bola " darsga kelgan"

}
elseif ( $bola -ceq "Damir") {
    Write-host $bola " darsga kelgan"

}
elseif ( $bola -ceq "Dilshod") {
    Write-host $bola " darsga kelgan"

}
elseif ( $bola -ceq "Begzod") {
    Write-host $bola " darsga kelgan"

}else {
    Write-host $bola " darsga kelmagangan"
}