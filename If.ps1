write-host "Yoshing Nechida? "
[int]$yosh = Read-Host

if ($yosh -eq 11) {
    Write-Host ("Salom")
}elseif ($yosh -eq 12) {
    Write-Host ("Assalom")
}elseif ($yosh -eq 12) {
    Write-Host ("Assalom1")
}elseif ($yosh -eq 13) {
    Write-Host ("Assalom2")
}elseif ($yosh -eq 14) {
    Write-Host ("Assalom3")
}else {
    write-host ("Xato")
}




