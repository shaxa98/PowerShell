$yosh = 20
if ($yosh -lt 7) {
    Write-Host "Hali maktab yoshiga yetmagan"
}elseif ( $yosh -eq 7) {
    Write-Host "Birinchi Sinf"
}elseif ( $yosh -eq 8) {
    Write-Host "Ikkinchi Sinf"
}elseif ( $yosh -eq 9) {
    Write-Host "Uchinchi Sinf"
}elseif ( $yosh -eq 10) {
    Write-Host "To'rtinchi Sinf"
}elseif ( $yosh -eq 11) {
    Write-Host "Beshinchi Sinf"
}elseif ( $yosh -eq 12) {
    Write-Host "Oltinchi Sinf"
}elseif ( $yosh -eq 13) {
    Write-Host "Yetinchi Sinf"
}elseif ( $yosh -eq 14) {
    Write-Host "Sakkizinchi Sinf"
}elseif ( $yosh -eq 15) {
    Write-Host "To'qizinchi Sinf"
}elseif ( $yosh -eq 16) {
    Write-Host "O'ninchi Sinf"
}elseif ( $yosh -eq 17) {
    Write-Host "O'nbirinchi Sinf"
}else {
    Write-Host "Maktab Yoshidan O'tgan" 
}
    
